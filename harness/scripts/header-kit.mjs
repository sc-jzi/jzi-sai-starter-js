#!/usr/bin/env node
/**
 * Generate the client's HEADER-AREA variants in the customer's own app copy (never in industry-verticals/prospera):
 *   Eyebrow     export const <Client>   hardcoded eyebrow bar: links, phone, search button, CTA button (+ the eyebrow-left / eyebrow-right placeholders,
 *                                       so ThemeSwitcher / LanguageSwitcher still work). Not CMS driven on purpose: the Navigation component cannot render it.
 *   Header      export const <Client>   copy of WithLogoImage (logo + header-right placeholder), logo sized like the prospect's
 *   Navigation  export const <Client>   the shared Navigation rendered TOP LEVEL ONLY (children dropped), styled like the prospect's menu
 * and the styles for all three, from the measured numbers in header-styles.json (header-styles.mjs).
 *
 *   node harness/scripts/header-kit.mjs --customer <customer> [--variant <Name>] [--dry-run]
 *
 * Inputs (demo folder): header-styles.json, nav.json (eyebrow links/phone/CTA), demo-plan.yaml (site.variantName, planned eyebrow pages).
 * Writes in industry-verticals/<customer>/:
 *   src/components/navigation/eyebrow-config.ts                      the hardcoded eyebrow content
 *   src/components/navigation/{Eyebrow,Header,Navigation}.tsx         export block between `// harness:header-kit:start/end` markers (re-running replaces it)
 *   src/assets/sass/variants/header/_<kebab>.scss (+ index.scss) and the @import in src/assets/sass/variants/index.scss
 * Variant Definitions with the same name are created in Sitecore by demo-site-bootstrap (step 2) for Eyebrow, Header and Navigation.
 */
import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { die, parseArgs, demoDir, customerApp, safeWrite, readJson, rootRel } from "./_lib.mjs";
import { parseYaml } from "./_yaml.mjs";

const { flags } = parseArgs(process.argv.slice(2));
const customer = flags.customer; if (!customer) die("need --customer");
const app = customerApp(customer), demo = demoDir(customer), dry = !!flags["dry-run"];
const planP = join(demo, "demo-plan.yaml"), plan = existsSync(planP) ? parseYaml(readFileSync(planP, "utf8")) : {};
const hs = readJson(join(demo, "header-styles.json")); if (!hs) die("header-styles.json missing: run node harness/scripts/header-styles.mjs --customer <customer> --url <prospect url> first");
const nav = readJson(join(demo, "nav.json"), {}) || {};
const pascal = (n) => String(n || "").replace(/&/g, " ").split(/[^A-Za-z0-9]+/).filter(Boolean).map((w) => w[0].toUpperCase() + w.slice(1)).join("");
const V = flags.variant || plan.site?.variantName || pascal(plan.client?.name || customer);
const kebab = V.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
const e = hs.eyebrow, h = hs.header;
const px = (n, d = 0) => (typeof n === "number" ? n : d);
const log = [];

// ---------- eyebrow content (hardcoded)
const siteOrigin = (() => { try { return new URL(hs.url || nav.url).origin; } catch { return ""; } })();
const abs = (href) => { if (!href) return "#"; if (/^(https?:|tel:|mailto:|#)/i.test(href)) return href; try { return new URL(href, siteOrigin || "https://example.com").href; } catch { return href; } };
const pages = (plan.site?.pages || []).filter((p) => p && p.path);
const route = (p) => "/" + p.path.replace(/^\/?home\/?/i, "");
const planned = (label) => { const p = pages.find((x) => String(x.displayName || "").toLowerCase() === String(label).toLowerCase()); return p ? route(p) : null; };
const links = (nav.eyebrow || []).map((l) => ({ label: l.label, href: planned(l.label) || abs(l.href) }));
const phoneX = (nav.eyebrowExtras || []).find((x) => x.kind === "phone"), ctaX = (nav.eyebrowExtras || []).find((x) => x.kind === "cta");
const cfg = { links, phone: phoneX ? { label: phoneX.label, href: /^tel:/i.test(phoneX.href || "") ? phoneX.href : `tel:${phoneX.label.replace(/[^\d+]/g, "")}` } : null, cta: ctaX ? { label: ctaX.label, href: planned(ctaX.label) || abs(ctaX.href) } : null, search: !!(e && e.search) || true };
const cfgTs = `// Generated by harness/scripts/header-kit.mjs from nav.json (measured on ${nav.url || hs.url || "the prospect site"}). Hardcoded on purpose: the demo's eyebrow bar is not CMS driven.\nexport const eyebrowConfig: {\n  links: { label: string; href: string }[];\n  phone: { label: string; href: string } | null;\n  cta: { label: string; href: string } | null;\n  search: boolean;\n} = ${JSON.stringify(cfg, null, 2)};\n`;

// ---------- styles
const ebBg = e?.bar?.background || "#000000", L = e?.links;
const rule = (t) => t ? [`font-family: ${/\s/.test(t.fontFamily || "") ? `"${t.fontFamily}"` : (t.fontFamily || "inherit")}, sans-serif;`.replace("inherit, sans-serif", "inherit"), `font-size: ${t.fontSize}px;`, `font-weight: ${t.fontWeight};`, `text-transform: ${t.textTransform};`, t.letterSpacing ? `letter-spacing: ${t.letterSpacing}px;` : "", t.color ? `color: ${t.color};` : ""].filter(Boolean).join("\n    ") : "";
const gap = px(L?.gap, 24);
// Menu alignment from where the prospect's menu actually sits: spread over (nearly) the full width -> equal spacing edge to edge; centred; or pushed to one side.
const vwid = hs.viewport || 1440, navSpan = h?.nav ? Math.round(h.nav.groupRight - h.nav.groupLeft) : 0, navMid = h?.nav ? (h.nav.groupLeft + h.nav.groupRight) / 2 : 0;
const navAlign = !h?.nav ? "flex-end" : navSpan / vwid >= 0.6 ? "space-between" : Math.abs(navMid - vwid / 2) < vwid * 0.06 ? "center" : navMid > vwid / 2 ? "flex-end" : "flex-start";
const scss = `// Generated by harness/scripts/header-kit.mjs from header-styles.json (measured ${hs.measuredAt || ""} on ${hs.url || ""}). Re-running the script overwrites this file: change the measurement or the script, not this file.
// Not theme variables on purpose: these are the prospect's measured header values (eyebrow bar, CTA button), not part of the site palette.
.component.eyebrow.variant-${kebab} {
  background: ${ebBg};
  .eyebrow-bar { display: flex; align-items: center; justify-content: flex-end; gap: ${gap}px; min-height: ${px(e?.bar?.height, 56)}px; }
  .eyebrow-slot-left { margin-right: auto; }
  .eyebrow-links { display: flex; align-items: center; gap: ${gap}px; list-style: none; margin: 0; padding: 0; }
  .eyebrow-links a, .eyebrow-phone {
    ${rule(L)}
    text-decoration: none; white-space: nowrap;
    &:hover { opacity: 0.8; }
  }
  .eyebrow-phone { ${e?.phone ? `font-size: ${e.phone.fontSize}px; font-weight: ${e.phone.fontWeight}; text-transform: ${e.phone.textTransform};` : ""} }
  .eyebrow-search { display: inline-flex; align-items: center; justify-content: center; background: none; border: 0; padding: 0; color: ${e?.search?.color || L?.color || "#ffffff"}; svg { width: ${Math.min(32, px(e?.search?.size, 24))}px; height: ${Math.min(32, px(e?.search?.size, 24))}px; } }
  .eyebrow-cta {
    display: inline-flex; align-items: center; text-decoration: none; white-space: nowrap;
    ${e?.cta ? `background: ${e.cta.background}; color: ${e.cta.color}; font-size: ${e.cta.fontSize}px; font-weight: ${e.cta.fontWeight}; text-transform: ${e.cta.textTransform}; border-radius: ${e.cta.borderRadius}px; padding: ${e.cta.paddingY}px ${e.cta.paddingX}px;${e.cta.border ? ` border: ${e.cta.border.width}px solid ${e.cta.border.color};` : ""}` : ""}
  }
  .eyebrow-slot-right { color: ${L?.color || "#ffffff"}; * { color: inherit; } }
}

.component.header.variant-${kebab} {
  background: ${h?.band?.background || "#ffffff"};
  ${h?.band?.borderBottom ? `border-bottom: ${h.band.borderBottom.width}px solid ${h.band.borderBottom.color};` : ""}
  ${h?.band?.boxShadow ? `box-shadow: ${h.band.boxShadow};` : ""}
  .row { min-height: ${px(h?.band?.height, 80)}px; align-items: center; }
  img { max-width: none; }
}

@media (min-width: 992px) {
  .component.navigation.variant-${kebab} {
    ${h?.menuBand ? `background: ${h.menuBand.background}; min-height: ${h.menuBand.height}px; display: flex; align-items: center;` : ""}
    nav { width: 100%; }
    nav > ul { display: flex; align-items: center; justify-content: ${navAlign}; gap: ${px(h?.nav?.gap, 24)}px; ${navAlign === "space-between" ? `width: 100%; max-width: ${navSpan}px; margin: 0 auto;` : "margin: 0;"} padding: 0; list-style: none; }
    nav > ul > li > ul { display: none !important; }   // top level only, whatever else comes through
    .navigation-title a {
      ${rule(h?.nav)}
      text-decoration: none; white-space: nowrap;
    }
  }
}
`;

// ---------- component blocks
const start = (n) => `// harness:header-kit:start ${n} ${V}`, end = (n) => `// harness:header-kit:end ${n} ${V}`;
const searchTop = px(e?.bar?.height, 56) + px(h?.band?.height, 90);
const eyebrowBlock = `${start("Eyebrow")}
/* ${V} variant: hardcoded eyebrow bar (links, phone, search, CTA) generated by harness/scripts/header-kit.mjs. The ThemeSwitcher / LanguageSwitcher placeholders stay. */
export const ${V} = (props: EyebrowProps): JSX.Element => {
  const id = props.params.RenderingIdentifier;
  const { page } = useSitecore();
  const [isSearchOpen, setIsSearchOpen] = useState(false);
  const searchPanelRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    if (!isSearchOpen) return;
    const handlePointerDown = (event: PointerEvent) => {
      if (searchPanelRef.current && !searchPanelRef.current.contains(event.target as Node)) setIsSearchOpen(false);
    };
    const handleKeyDown = (event: KeyboardEvent) => {
      if (event.key === 'Escape') setIsSearchOpen(false);
    };
    document.addEventListener('pointerdown', handlePointerDown);
    document.addEventListener('keydown', handleKeyDown);
    return () => {
      document.removeEventListener('pointerdown', handlePointerDown);
      document.removeEventListener('keydown', handleKeyDown);
    };
  }, [isSearchOpen]);

  return (
    <>
      <div
        className={\`component eyebrow variant-${kebab} relative z-[60] \${props.params.styles?.trimEnd() ?? ''}\`}
        id={id || undefined}
      >
        <div className={\`container container-\${props.params?.ContainerWidth?.toLowerCase()}-fluid\`}>
          <div className="eyebrow-bar">
            <div className="eyebrow-slot eyebrow-slot-left">
              <AppPlaceholder name="eyebrow-left" rendering={props.rendering} page={page} componentMap={props.componentMap} />
            </div>
            <ul className="eyebrow-links">
              {eyebrowConfig.links.map((link) => (
                <li key={link.label}>
                  <a href={link.href}>{link.label}</a>
                </li>
              ))}
            </ul>
            {eyebrowConfig.phone && (
              <a className="eyebrow-phone" href={eyebrowConfig.phone.href}>
                {eyebrowConfig.phone.label}
              </a>
            )}
            {eyebrowConfig.search && (
              <button
                type="button"
                aria-label="Open search"
                aria-expanded={isSearchOpen}
                aria-controls="site-search-panel"
                onClick={() => setIsSearchOpen(true)}
                className="eyebrow-search"
              >
                <svg aria-hidden="true" fill="none" viewBox="0 0 24 24" stroke="currentColor">
                  <circle cx="11" cy="11" r="7" strokeWidth="2" />
                  <path d="m16.25 16.25 4 4" strokeWidth="2" strokeLinecap="round" />
                </svg>
              </button>
            )}
            {eyebrowConfig.cta && (
              <a className="eyebrow-cta" href={eyebrowConfig.cta.href}>
                {eyebrowConfig.cta.label}
              </a>
            )}
            <div className="eyebrow-slot eyebrow-slot-right">
              <AppPlaceholder name="eyebrow-right" rendering={props.rendering} page={page} componentMap={props.componentMap} />
            </div>
          </div>
        </div>
      </div>

      {isSearchOpen && (
        <>
          <button
            type="button"
            aria-label="Close search"
            onClick={() => setIsSearchOpen(false)}
            className="fixed inset-x-0 bottom-0 top-[${searchTop}px] z-[40] cursor-default bg-white/20 backdrop-blur-md"
          />
          <div
            id="site-search-panel"
            ref={searchPanelRef}
            role="search"
            className="fixed inset-x-0 top-[${searchTop}px] z-[50] bg-[#f5f5f5] px-6 py-10 shadow-sm"
            onClick={(event) => event.stopPropagation()}
          >
            <div className="mx-auto max-w-[1200px]">
              <PreviewSearch isOpen={isSearchOpen} setIsSearchOpen={setIsSearchOpen} />
            </div>
          </div>
        </>
      )}
    </>
  );
};
${end("Eyebrow")}
`;
const lw = px(h?.logo?.width, 200), lh = px(h?.logo?.height, 50);
const headerBlock = `${start("Header")}
/* ${V} variant: WithLogoImage with the prospect's logo size and header band, generated by harness/scripts/header-kit.mjs */
export const ${V} = (props: HeaderProps): JSX.Element => {
  const id = props.params.RenderingIdentifier;
  const sxaStyles = \`\${props.params?.styles || ''}\`;
  const { page } = useSitecore();

  return (
    <div className={\`component header variant-${kebab} \${sxaStyles}\`} id={id ? id : undefined}>
      <div className={\`container container-\${props.params?.ContainerWidth?.toLowerCase()}-fluid\`}>
        <div className="row align-items-center">
          <div className="col-auto">
            <a href="/">
              <NextImage field={props.fields.LogoImage} width={${lw}} height={${lh}} />
            </a>
          </div>
          <div className="col">
            <AppPlaceholder name="header-right" rendering={props.rendering} page={page} componentMap={props.componentMap} />
          </div>
        </div>
      </div>
    </div>
  );
};
${end("Header")}
`;
const navBlock = `${start("Navigation")}
/* ${V} variant: the shared Navigation, TOP LEVEL ONLY (children are dropped), styled by variants/header/_${kebab}.scss. Generated by harness/scripts/header-kit.mjs */
export const ${V} = (props: NavigationProps): JSX.Element => {
  const topLevel = Object.fromEntries(
    Object.entries(props.fields ?? {}).map(([key, value]) => [key, value ? { ...(value as Fields), Children: [] } : value])
  );
  return (
    <Default
      {...props}
      fields={topLevel as unknown as Fields}
      params={{ ...props.params, Styles: \`\${props.params?.Styles ?? ''} variant-${kebab}\` }}
    />
  );
};
${end("Navigation")}
`;

// ---------- write
const wr = (rel, content) => { const abs2 = join(app, rel); log.push(rel); if (!dry) { mkdirSync(dirname(abs2), { recursive: true }); safeWrite(customer, abs2, content); } };
const patchTsx = (file, name, block, importLine) => {
  const abs2 = join(app, "src/components/navigation", file);
  if (!existsSync(abs2)) { console.log(`⚠ ${rootRel(abs2)} not found: the customer app copy is missing ${file}; copy it from industry-verticals/prospera first.`); process.exitCode = 3; return; }
  let s = readFileSync(abs2, "utf8"); const nl = s.includes("\r\n") ? "\r\n" : "\n"; s = s.replace(/\r\n/g, "\n");
  const re = new RegExp(`\\n?// harness:header-kit:start ${name} [^\\n]*\\n[\\s\\S]*?// harness:header-kit:end ${name} [^\\n]*\\n?`, "g");
  if (re.test(s)) s = s.replace(re, "\n"); else if (new RegExp(`export const ${V}\\b`).test(s)) { console.log(`⚠ ${file} already has a hand-written export ${V}: left untouched.`); return; }
  if (importLine && !s.includes(importLine)) { const imports = [...s.matchAll(/^import .*;$/gm)]; const last = imports[imports.length - 1]; const at = last ? last.index + last[0].length : 0; s = s.slice(0, at) + "\n" + importLine + s.slice(at); }
  s = s.replace(/\s+$/, "") + "\n\n" + block;
  log.push(`src/components/navigation/${file}`); if (!dry) safeWrite(customer, abs2, s.replace(/\n/g, nl));
};
wr("src/components/navigation/eyebrow-config.ts", cfgTs);
patchTsx("Eyebrow.tsx", "Eyebrow", eyebrowBlock, "import { eyebrowConfig } from './eyebrow-config';");
patchTsx("Header.tsx", "Header", headerBlock);
patchTsx("Navigation.tsx", "Navigation", navBlock);
wr(`src/assets/sass/variants/header/_${kebab}.scss`, scss);
const idx = join(app, "src/assets/sass/variants/header/index.scss"), idxLine = `@import "${kebab}";`;
const idxOld = existsSync(idx) ? readFileSync(idx, "utf8") : "";
if (!idxOld.includes(idxLine)) wr("src/assets/sass/variants/header/index.scss", (idxOld ? idxOld.replace(/\s*$/, "\n") : "") + idxLine + "\n");
const top = join(app, "src/assets/sass/variants/index.scss");
if (existsSync(top)) { const t = readFileSync(top, "utf8"); if (!/@import\s+["']header["']/.test(t)) wr("src/assets/sass/variants/index.scss", t.replace(/\s*$/, "\n") + '@import "header";\n'); }
else console.log("⚠ src/assets/sass/variants/index.scss not found: import the header folder from your main stylesheet by hand.");
console.log(`${dry ? "[dry run] would write" : "✅ wrote"} ${V}:\n  - ${log.join("\n  - ")}`);
console.log(`Eyebrow content (hardcoded): ${cfg.links.map((l) => l.label).join(" | ") || "(none)"}${cfg.phone ? ` | phone ${cfg.phone.label}` : ""}${cfg.cta ? ` | CTA ${cfg.cta.label}` : ""} | search`);
if (!e) console.log("⚠ no eyebrow measurements in header-styles.json: the eyebrow styles used neutral defaults. Measure the bar by eye from the screenshot and re-run.");
if (!h) console.log("⚠ no header measurements in header-styles.json: the header/navigation styles used neutral defaults.");
console.log("Next: Variant Definitions named exactly `" + V + "` under Presentation/Headless Variants/{Eyebrow,Header,Navigation} (demo-site-bootstrap step 2), then type-check the app.");
