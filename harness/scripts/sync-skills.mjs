#!/usr/bin/env node
/**
 * Skills live ONCE, in .skills/<name>/ (SKILL.md plus its references and examples). Cursor and Claude Code each get generated stubs:
 *   .cursor/skills/<name>/SKILL.md   and   .claude/skills/<name>/SKILL.md   same name + description (so both tools list the skill),
 *                                                                         body: "read .skills/<name>/SKILL.md and follow it"
 *   .cursor/skills/<path>.md       a pointer for every other Markdown file, so old links keep working
 *
 *   node harness/scripts/sync-skills.mjs            write / refresh the stubs, remove stubs whose source is gone
 *   node harness/scripts/sync-skills.mjs --check    exit 1 when a stub is missing or stale, or a real file sits where only stubs belong (.githooks/pre-commit)
 *
 * Edit skills ONLY under .skills/. A stub is never edited by hand: it carries the GENERATED marker and is rewritten here.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { ROOT, parseArgs } from "./_lib.mjs";

const { flags } = parseArgs(process.argv.slice(2));
const check = !!flags.check;
const SRC = join(ROOT, ".skills"), TARGETS = { cursor: join(ROOT, ".cursor", "skills"), claude: join(ROOT, ".claude", "skills") };
const MARK = "<!-- GENERATED by harness/scripts/sync-skills.mjs";
if (!existsSync(SRC)) { console.error(".skills/ not found"); process.exit(2); }

const walk = (d) => readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(join(d, e.name)) : [join(d, e.name)]));
const rel = (p, base) => relative(base, p).replace(/\\/g, "/");
const frontmatter = (text) => { const m = text.replace(/^﻿/, "").match(/^---\r?\n[\s\S]*?\r?\n---\r?\n/); return m ? m[0].replace(/\r\n/g, "\n") : null; };

// what the stubs must be
const want = new Map();   // absolute stub path -> content
for (const f of walk(SRC).filter((p) => p.endsWith(".md"))) {
  const r = rel(f, SRC), isSkill = /^[^/]+\/SKILL\.md$/.test(r);
  const header = `${MARK} from .skills/${r}: edit the source, not this file -->\n`;
  if (isSkill) {
    const fm = frontmatter(readFileSync(f, "utf8"));
    if (!fm) { console.error(`✖ .skills/${r} has no frontmatter (name, description): a skill needs it to be listed`); process.exitCode = 1; continue; }
    const name = r.split("/")[0];
    const body = `${fm}${header}\n# ${name}\n\nThis skill is maintained in \`.skills/${name}/SKILL.md\` (one copy, shared by Cursor and Claude Code).\nRead that file now and follow it exactly. Paths in it are relative to the repository root.\n`;
    want.set(join(TARGETS.cursor, r), body);
    want.set(join(TARGETS.claude, r), body);
  } else {
    want.set(join(TARGETS.cursor, r), `${header}\nThis file is maintained in \`.skills/${r}\`. Read that file instead.\n`);
  }
}

let stale = 0, written = 0, removed = 0, foreign = [];
for (const [p, body] of want) {
  const cur = existsSync(p) ? readFileSync(p, "utf8") : null;
  if (cur === body) continue;
  if (cur !== null && !cur.includes(MARK)) foreign.push(p);   // a real file where a stub belongs: someone edited the old location
  stale++;
  if (!check && !(cur !== null && !cur.includes(MARK))) { mkdirSync(dirname(p), { recursive: true }); writeFileSync(p, body); written++; }
}
for (const base of Object.values(TARGETS)) {
  if (!existsSync(base)) continue;
  for (const p of walk(base)) {
    if (want.has(p)) continue;
    const text = statSync(p).size < 1_000_000 ? readFileSync(p, "utf8") : "";
    if (text.includes(MARK)) { stale++; if (!check) { rmSync(p); removed++; } }   // stub whose source is gone
    else foreign.push(p);                                                          // a real file in a stub-only folder
  }
}
for (const p of foreign) console.log(`✖ ${rel(p, ROOT)} is a real file in a stub-only folder: move its content to .skills/ and run sync-skills.mjs`);
if (check) {
  if (stale || foreign.length) { console.log(`✖ skill stubs out of date (${stale} stub(s)): run node harness/scripts/sync-skills.mjs`); process.exit(1); }
  console.log(`✔ skill stubs match .skills/ (${want.size} stub(s))`); process.exit(process.exitCode ?? 0);
}
console.log(`✔ ${written} stub(s) written, ${removed} removed, ${want.size} in total (.cursor/skills + .claude/skills)`);
process.exit(foreign.length ? 1 : (process.exitCode ?? 0));
