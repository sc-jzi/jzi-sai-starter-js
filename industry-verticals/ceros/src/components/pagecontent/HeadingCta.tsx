/* Ceros variant: a dark title band in Ceros type (Fustat, light weight); eyebrow, text and link only when filled (or in Pages) */
const CerosHeading = ({ props, modifier }: { props: HeadingCtaProps; modifier: string }): JSX.Element => {
  const id = props.params.RenderingIdentifier;
  const { page } = useSitecore();
  const isPageEditing = page.mode.isEditing;
  const sxaStyles = `${props.params?.styles || ''}`;
  const f = props.fields;

  return (
    <div className={`component heading-cta variant-ceros ${modifier} ${sxaStyles}`} id={id ? id : undefined}>
      <div className="ceros-heading__inner">
        {(isPageEditing || f?.Eyebrow?.value) && <Text field={f?.Eyebrow} tag="p" className="ceros-heading__eyebrow" />}
        <Text field={f?.Heading} tag="h1" className="ceros-heading__title" />
        {(isPageEditing || f?.Text?.value) && <Text field={f?.Text} tag="p" className="ceros-heading__text" />}
        {(isPageEditing || f?.Link?.value?.href) && <Link field={f?.Link} className="ceros-btn ceros-btn--pill" />}
      </div>
    </div>
  );
};

export const Ceros = (props: HeadingCtaProps): JSX.Element => <CerosHeading props={props} modifier="ceros-heading--section" />;

/* Ceros page-title look: the title-only band of the menu pages */
export const CerosPageTitle = (props: HeadingCtaProps): JSX.Element => (
  <CerosHeading props={props} modifier="ceros-heading--page-title" />
);
